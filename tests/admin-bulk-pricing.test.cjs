'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync(__dirname+'/../admin-bulk-pricing.js','utf8');
const sandbox={window:{MasterCloud:{}}};vm.runInNewContext(source,sandbox,{filename:'admin-bulk-pricing.js'});
const mod=sandbox.window.MasterBulkPricing;
assert.equal(typeof mod.mount,'function');
assert.equal(mod.priceAfter(88000,5),92400);
assert.equal(mod.priceAfter(88000,-25),66000);
assert.equal(mod.priceAfter(100,-50),null);
assert.equal(mod.priceAfter(100000000,100),null);
assert.equal(mod.priceAfter(88000,101),null);
assert.equal(mod.priceAfter(88000,-51),null);
assert.equal(mod.priceAfter(88000,0),88000);
assert(source.includes('ready.signature!==fingerprint()'),'selection must match preview');
assert(source.includes('expected_version:p.updated_at'),'server version must be checked');
assert(source.includes('if(!confirm('),'price change confirmation required');
assert(fs.readFileSync(__dirname+'/../admin-control-center.js','utf8').includes('MasterBulkPricing?.mount'),'owner panel must mount pricing');
assert(require('../scripts/public-assets.json').includes('admin-bulk-pricing.js'),'price tool must be published');
console.log('PASS: owner price simulator, bounded changes, preview approval and version checks.');
