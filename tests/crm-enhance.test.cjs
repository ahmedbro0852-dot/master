'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync(__dirname+'/../crm-enhance.js','utf8');
const mock={window:{MasterCloud:{}}};
vm.runInNewContext(source,mock,{filename:'crm-enhance.js'});
const tools=mock.window.MasterCRMEnhance;
assert.equal(typeof tools.mount,'function');
assert.equal(typeof tools.attachForm,'function');
assert.equal(tools.validImage({type:'image/png',size:1024}),true);
assert.equal(tools.validImage({type:'image/jpeg',size:4*1024*1024}),true);
assert.equal(tools.validImage({type:'image/webp',size:4*1024*1024+1}),false);
assert.equal(tools.validImage({type:'image/svg+xml',size:1200}),false);
assert.equal(tools.validImage({type:'text/html',size:120}),false);
assert.equal(tools.safeFilename('evil<script>.png'),'evilscript.png');
assert.equal(tools.imagePath('order-1','uuid-2','image/png'),'order-1/uuid-2.png');
assert(source.includes("createSignedUrl(entry.object_path,300)"),'private storage must use expiring URLs');
assert(source.includes('if(!isAdmin())return;'),'only authorized admin may open order tools');
assert(source.includes("eq('updated_at',order.updated_at)"),'follow-up notes require concurrency check');
assert(source.includes('MAX_PER_ORDER=12'),'photo upload limit should be enforced');
assert(source.includes("TEMPLATES_KEY"),'service entry templates must persist locally');
assert(!source.includes('getPublicUrl('),'customer photos must not be public');
assert(!source.includes('service_role'),'do not expose privileged keys to browsers');
const page=fs.readFileSync(__dirname+'/../management.html','utf8');
assert(page.includes('crm-enhance.js?v=20261105-photos1'));
const mg=fs.readFileSync(__dirname+'/../management.js','utf8');
assert(mg.includes('data-crm-photos')&&mg.includes('data-crm-followup'),'order actions missing');
assert(mg.includes('MasterCRMEnhance?.mount')&&mg.includes('MasterCRMEnhance?.attachForm'),'registration integration missing');
assert(require('../scripts/public-assets.json').includes('crm-enhance.js'),'admin module not published');
console.log('PASS: admin-only order photos, safe formats/size, signed URLs, follow-up notes, quick service templates.');
