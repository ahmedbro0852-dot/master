'use strict';
// Pure unit tests: no authentication, network requests, or financial mutations.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const file=name=>fs.readFileSync(path.join(root,name),'utf8');
const source=file('admin-control-center.js');
const sandbox={window:{MasterCloud:{},MasterStore:{escapeHtml:String,formatCurrency:String}}};
vm.runInNewContext(source,sandbox,{filename:'admin-control-center.js'});
const module=sandbox.window.MasterAdvancedAdmin;
assert.equal(typeof module.render,'function');
assert.equal(typeof module.csvCell,'function');
assert.equal(module.csvCell('=2+2'),'"\'=2+2"');
assert.equal(module.csvCell(' +SUM(1,2)'),'"\' +SUM(1,2)"');
assert.equal(module.csvCell('@injection'),'"\'@injection"');
assert.equal(module.csvCell('hello, "world"'),'"hello, ""world"""');
assert.equal(module.csvCell('10'),'"10"');
const report=module.csvRows(['Name','Note'],[['a,b','=SUM(1,1)'],['Customer','Line 1\nLine 2']]);
assert.equal(report.charCodeAt(0),65279,'Excel UTF-8 BOM expected');
assert(report.includes('"a,b","\'=SUM(1,1)"'),'formula-unsafe CSV content');
assert(report.includes('Line 1\nLine 2'),'multiline fields must be safely quoted');
assert(report.includes('\r\n'),'CSV must use CRLF');
const admin=file('admin.js'),html=file('admin.html'),css=file('admin-control-center.css');
assert(admin.includes('master_store_admin_snapshot'),'server-side admin authorization gate must be kept');
assert(admin.includes("['advanced','مركز التحكم المتقدم'"),'advanced tab missing');
assert(admin.includes('window.MasterAdvancedAdmin.render'),'advanced tab not wired');
assert(html.includes('admin-control-center.js?v='),'admin module not included');
assert(html.includes('admin-control-center.css?v='),'admin stylesheet not included');
assert(css.includes('.power-table'),'responsive plan table styles missing');
for(const name of ['admin-control-center.js','admin-control-center.css'])
 assert(require('../scripts/public-assets.json').includes(name),'admin asset missing from public build');
assert(source.includes('master_store_admin_plan'),'writes must reuse protected administrator procedure');
assert(source.includes('expected_version:p.updated_at'),'avoid stale overwrites');
assert(source.includes('if(!confirm('),'bulk changes require confirmation');
assert(!source.includes('service_role'),'do not ship privileged API keys to the browser');
console.log('PASS: administrator-only module, safe CSV, bulk action confirmation, version checks, and public asset wiring.');
